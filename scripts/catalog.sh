#!/usr/bin/env bash
# catalog.sh — regenerate CATALOG.md from role + skill frontmatter
#
# Walks roles/*/ROLE.md, roles/*/skills/*/SKILL.md, and skills/*/SKILL.md
# and writes a dispatcher-friendly catalog to CATALOG.md at the repo root.
#
# Run after adding, renaming, or re-describing a role or skill. The
# generated CATALOG.md is committed so consumers don't need to run
# anything to use the dispatcher.

set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

OUT="CATALOG.md"

# Extract a top-level YAML field's first-line value from a markdown file's
# frontmatter. Frontmatter is the block between the first two '---' lines.
yaml_field() {
  local field="$1"; local file="$2"
  awk -v fld="$field" '
    BEGIN { sep = 0 }
    /^---$/ { sep++; if (sep == 2) exit; next }
    sep == 1 {
      pattern = "^" fld ":[[:space:]]*"
      if (match($0, pattern)) {
        line = substr($0, RSTART + RLENGTH)
        sub(/[[:space:]]+$/, "", line)
        print line
        exit
      }
    }
  ' "$file"
}

{
  echo "# Hornero catalog"
  echo ""
  echo "> Generated by \`scripts/catalog.sh\` — do not hand-edit. Re-run after"
  echo "> adding, renaming, or re-describing a role or skill."
  echo ">"
  echo "> One-liner index used by the dispatcher protocol in [\`CLAUDE.md\`](CLAUDE.md)."
  echo "> Match the user's prompt against the rows here, then load only the"
  echo "> ROLE.md + SKILL.md you actually need."
  echo ""

  echo "## Roles"
  echo ""
  echo "| Role | When to invoke |"
  echo "|---|---|"
  for role_md in roles/*/ROLE.md; do
    [[ -f "$role_md" ]] || continue
    name=$(yaml_field name "$role_md")
    desc=$(yaml_field description "$role_md")
    [[ -n "$name" ]] || continue
    echo "| \`${name}\` | ${desc} |"
  done
  echo ""

  if ls skills/*/SKILL.md >/dev/null 2>&1; then
    echo "## Cross-role skills"
    echo ""
    echo "> Process skills that any role can invoke. The dispatcher should reach"
    echo "> for \`multi-role-review\` whenever two or more roles match strongly."
    echo ""
    echo "| Skill | Type | When to invoke |"
    echo "|---|---|---|"
    for skill_md in skills/*/SKILL.md; do
      [[ -f "$skill_md" ]] || continue
      # Skip plugin-loader symlinks pointing at per-role skills — those are
      # listed under their role's section below.
      skill_dir=$(dirname "$skill_md")
      [[ -L "$skill_dir" ]] && continue
      name=$(yaml_field name "$skill_md")
      type=$(yaml_field type "$skill_md")
      desc=$(yaml_field description "$skill_md")
      [[ -n "$name" ]] || continue
      echo "| \`${name}\` | ${type} | ${desc} |"
    done
    echo ""
  fi

  if ls resources/*/RESOURCE.md >/dev/null 2>&1; then
    echo "## Resources"
    echo ""
    echo "> External data sources skills can read or write via MCP. Skills opt in"
    echo "> via their \`resources:\` frontmatter. Stretch entries are not yet"
    echo "> wired to a mature MCP server — the fallback prose still works."
    echo ""
    echo "| Resource | Status | MCP server | Used by |"
    echo "|---|---|---|---|"
    for res_md in resources/*/RESOURCE.md; do
      [[ -f "$res_md" ]] || continue
      name=$(yaml_field name "$res_md")
      status=$(yaml_field status "$res_md")
      [[ -n "$name" ]] || continue
      mcp_server=$(awk '
        /^---$/ { sep++; if (sep == 2) exit; next }
        sep == 1 && /^mcp:[[:space:]]*$/ { in_mcp=1; next }
        sep == 1 && in_mcp && /^[[:space:]]+server:/ {
          sub(/^[[:space:]]+server:[[:space:]]*/, ""); gsub(/^"|"$/, ""); print; exit
        }
        sep == 1 && in_mcp && /^[^[:space:]]/ { in_mcp=0 }
      ' "$res_md")
      [[ -z "$mcp_server" ]] && mcp_server="—"
      used_by_count=$(awk '
        /^---$/ { sep++; if (sep == 2) exit; next }
        sep == 1 && /^used_by:[[:space:]]*$/ { in_block=1; next }
        sep == 1 && in_block && /^[[:space:]]+-/ { n++; next }
        sep == 1 && in_block && /^[^[:space:]]/ { in_block=0 }
        END { print (n ? n : 0) }
      ' "$res_md")
      echo "| \`${name}\` | ${status} | \`${mcp_server}\` | ${used_by_count} skill(s) |"
    done
    echo ""
  fi

  echo "## Role skills"
  echo ""
  for role_md in roles/*/ROLE.md; do
    [[ -f "$role_md" ]] || continue
    role_dir=$(dirname "$role_md")
    role_name=$(yaml_field name "$role_md")
    [[ -n "$role_name" ]] || continue

    # Skip if the role has no shipped skills yet.
    if ! ls "$role_dir"/skills/*/SKILL.md >/dev/null 2>&1; then
      continue
    fi

    echo "### ${role_name}"
    echo ""
    echo "| Skill | Type | When to invoke |"
    echo "|---|---|---|"
    for skill_md in "$role_dir"/skills/*/SKILL.md; do
      name=$(yaml_field name "$skill_md")
      type=$(yaml_field type "$skill_md")
      desc=$(yaml_field description "$skill_md")
      [[ -n "$name" ]] || continue
      echo "| \`${name}\` | ${type} | ${desc} |"
    done
    echo ""
  done
} > "$OUT"

echo "✓ wrote $OUT ($(wc -l < "$OUT" | tr -d ' ') lines)"
