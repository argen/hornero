#!/usr/bin/env bash
# build-codex-agents.sh — generate Codex-format TOML subagents from the
# canonical Claude-format Markdown reviewer files in agents/.
#
# Claude Code reads agents/<name>.md (Markdown with YAML frontmatter).
# Codex reads .codex/agents/<name>.toml (TOML with `name`,
# `description`, `sandbox_mode`, `developer_instructions`). Both formats
# describe the same reviewer; this script keeps them in sync.
#
# Canonical source: agents/*.md (author-facing — edit these).
# Generated mirror: .codex/agents/*.toml (committed; never hand-edit).
#
# Idempotent: re-running rewrites .codex/agents/<name>.toml from the
# current agents/<name>.md content. Safe to run any time.
#
# Usage:
#   ./scripts/build-codex-agents.sh

set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"

mkdir -p .codex/agents

# Extract a top-level YAML field's first-line value from a markdown file's
# frontmatter. Frontmatter is the block between the first two '---' lines.
yaml_field() {
  local field="$1"; local file="$2"
  awk -v fld="$field" '
    BEGIN { sep = 0 }
    /^---$/ { sep++; if (sep == 2) exit; next }
    sep == 1 {
      pattern = "^" fld ":[[:space:]]*"
      if (match($0, pattern)) {
        line = substr($0, RSTART + RLENGTH)
        sub(/[[:space:]]+$/, "", line)
        print line
        exit
      }
    }
  ' "$file"
}

# Print everything AFTER the second '---' line (the markdown body).
body_after_frontmatter() {
  local file="$1"
  awk 'BEGIN { sep = 0 } /^---$/ { sep++; next } sep >= 2 { print }' "$file"
}

generated=0
for src in agents/*.md; do
  [[ -f "$src" ]] || continue
  [[ "$(basename "$src")" == ".gitkeep" ]] && continue

  name=$(yaml_field name "$src")
  description=$(yaml_field description "$src")

  if [[ -z "$name" ]]; then
    echo "  ✗ $src missing 'name:' frontmatter — skipping" >&2
    exit 1
  fi
  if [[ -z "$description" ]]; then
    echo "  ✗ $src missing 'description:' frontmatter — skipping" >&2
    exit 1
  fi

  target=".codex/agents/${name}.toml"

  # Build the TOML.
  # - name and description are quoted strings (escape backslashes and double quotes).
  # - sandbox_mode is read-only for all reviewers (read-only is the explore/edit
  #   separation invariant from DISPATCHER.md §5).
  # - developer_instructions uses TOML literal multi-line strings ('''…''')
  #   which preserve content verbatim; the only forbidden substring is '''.
  body=$(body_after_frontmatter "$src")
  if [[ "$body" == *"'''"* ]]; then
    echo "  ✗ $src body contains ''' — TOML literal triple-quote cannot embed it" >&2
    exit 1
  fi

  esc_description=$(printf '%s' "$description" | sed -e 's/\\/\\\\/g' -e 's/"/\\"/g')

  {
    echo "# Generated by scripts/build-codex-agents.sh from agents/$(basename "$src")."
    echo "# Do not hand-edit. Re-run the script after editing the Markdown source."
    echo ""
    echo "name = \"${name}\""
    echo "description = \"${esc_description}\""
    echo "sandbox_mode = \"read-only\""
    echo ""
    echo "developer_instructions = '''"
    printf '%s\n' "$body"
    echo "'''"
  } > "$target"

  generated=$((generated+1))
  echo "  ✓ ${target}"
done

echo
echo "✓ build-codex-agents: $generated TOML agents written to .codex/agents/"
